"""
Dataclass definitions for prediction results.

This module contains data structures returned by the inference prediction pipeline.
"""
from dataclasses import dataclass

@dataclass(frozen=True)
class PredictionResult:
    """
    Stores the prediction result generated by the trained machine learning model.

    Attributes
    ----------
    prediction : int
        Predicted class label.

    probability : float
        Probability of the predicted positive class.
    """
    prediction:int
    probability:float